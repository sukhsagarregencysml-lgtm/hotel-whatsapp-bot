const PDFDocument = require('pdfkit');
const fs = require('fs');
const path = require('path');

// items = [{ name, qty, price }]
async function generateRestaurantBill({
  billNo, date, guestName, room, hotelName,
  items, total
}) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', margin: 40 });
    const filePath = path.join('/tmp', `zaika-bill-${billNo}.pdf`);
    const stream = fs.createWriteStream(filePath);
    doc.pipe(stream);

    const GOLD = '#C9A84C';
    const DARK = '#1a1a2e';
    const GRAY = '#666666';
    const LIGHT = '#f5f5f5';

    // Header
    doc.rect(0, 0, 595, 100).fill(DARK);
    doc.fillColor(GOLD).fontSize(24).font('Helvetica-Bold')
       .text('ZAIKA RESTAURANT', 40, 28, { align: 'center' });
    doc.fillColor('#ffffff').fontSize(10).font('Helvetica')
       .text(hotelName || 'Hotel Sukhsagar Regency', 40, 60, { align: 'center' });
    doc.fillColor('#ffffff').fontSize(9)
       .text('In-house Restaurant', 40, 76, { align: 'center' });

    // Title bar
    doc.rect(0, 100, 595, 35).fill(GOLD);
    doc.fillColor('#fff').fontSize(14).font('Helvetica-Bold')
       .text('FOOD BILL', 40, 110, { align: 'center' });

    // Bill & date info
    doc.rect(40, 148, 240, 55).fill(LIGHT).stroke('#eee');
    doc.rect(315, 148, 240, 55).fill(LIGHT).stroke('#eee');

    doc.fillColor(GRAY).fontSize(9).font('Helvetica').text('BILL NO', 55, 158);
    doc.fillColor(DARK).fontSize(12).font('Helvetica-Bold').text(billNo, 55, 170);

    doc.fillColor(GRAY).fontSize(9).font('Helvetica').text('DATE', 330, 158);
    doc.fillColor(DARK).fontSize(12).font('Helvetica-Bold').text(date, 330, 170);

    function section(title, y) {
      doc.rect(40, y, 515, 22).fill(GOLD);
      doc.fillColor('#fff').fontSize(10).font('Helvetica-Bold').text(title, 50, y + 6);
      return y + 22;
    }
    function row(label, value, y, shade) {
      if (shade) doc.rect(40, y, 515, 22).fill('#fafafa');
      doc.fillColor(GRAY).fontSize(9).font('Helvetica').text(label, 50, y + 6);
      doc.fillColor(DARK).fontSize(10).font('Helvetica-Bold').text(String(value), 200, y + 6);
      return y + 22;
    }

    let y = section('GUEST DETAILS', 218);
    y = row('Guest Name', guestName, y, false);
    y = row('Room No.', room, y, true);

    // Items table
    y = section('ORDER ITEMS', y + 8);
    doc.rect(40, y, 515, 20).fill('#eeeeee');
    doc.fillColor(GRAY).fontSize(9).font('Helvetica-Bold')
       .text('ITEM', 50, y + 5)
       .text('QTY', 350, y + 5)
       .text('PRICE', 410, y + 5)
       .text('AMOUNT', 480, y + 5);
    y += 20;

    let shade = false;
    (items || []).forEach(item => {
      if (shade) doc.rect(40, y, 515, 20).fill('#fafafa');
      const amount = (item.qty || 1) * (item.price || 0);
      doc.fillColor(DARK).fontSize(9).font('Helvetica')
         .text(item.name || '-', 50, y + 5, { width: 280 })
         .text(String(item.qty || 1), 350, y + 5)
         .text('Rs.' + Math.round(item.price || 0).toLocaleString('en-IN'), 410, y + 5)
         .text('Rs.' + Math.round(amount).toLocaleString('en-IN'), 480, y + 5);
      y += 20;
      shade = !shade;
    });

    // Total row
    y += 8;
    doc.rect(40, y, 515, 28).fill(GOLD);
    doc.fillColor('#fff').fontSize(11).font('Helvetica-Bold').text('TOTAL AMOUNT', 50, y + 8);
    doc.fillColor('#fff').fontSize(13).font('Helvetica-Bold')
       .text('Rs.' + Math.round(total).toLocaleString('en-IN'), 480, y + 7);
    y += 28;

    // Footer
    doc.rect(0, 770, 595, 72).fill(DARK);
    doc.fillColor(GOLD).fontSize(10).font('Helvetica-Bold')
       .text('Zaika Restaurant', 40, 782, { align: 'center' });
    doc.fillColor('#fff').fontSize(9).font('Helvetica')
       .text('Thank you for dining with us!', 40, 798, { align: 'center' });
    doc.fillColor(GRAY).fontSize(8)
       .text('Generated by HotelEase PMS | ' + new Date().toLocaleString('en-IN'), 40, 816, { align: 'center' });

    doc.end();
    stream.on('finish', () => resolve(filePath));
    stream.on('error', reject);
  });
}

module.exports = { generateRestaurantBill };
